test("cancelled request cannot display a late report and failure can retry", async ({ page }) => {
  await page.goto("/"); await fillBirth(page);
  await page.getByRole("button", { name: "生成命盘", exact: true }).click();
  await expect(page.getByRole("button", { name: "开始 AI 解读（示例）" })).toBeVisible();
  let release: () => void = () => {};
  const gate = new Promise<void>((resolve) => { release = resolve; });
  await page.route("**/api/chart/interpret", async (route) => { await gate; await route.abort().catch(() => {}); });
  await page.getByRole("button", { name: "开始 AI 解读（示例）" }).click();
  await expect(page.getByRole("heading", { name: "示例报告整理" })).toBeVisible();
  await page.getByRole("button", { name: "取消，返回命盘" }).click(); release();
  await expect(page.getByRole("heading", { name: "林清月的紫微命盘" })).toBeVisible();
  await page.unroute("**/api/chart/interpret");
  await page.route("**/api/chart/interpret", (route) => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: "测试服务不可用" }) }), { times: 1 });
  await page.getByRole("button", { name: "开始 AI 解读（示例）" }).click();
  await expect(page.getByRole("alert").filter({ hasText: "测试服务不可用" })).toHaveText("测试服务不可用");
  await page.getByRole("button", { name: "重试解读（示例）" }).click();
  await expect(page.getByRole("heading", { name: "林清月的命盘阅读示例" })).toBeVisible();
});

