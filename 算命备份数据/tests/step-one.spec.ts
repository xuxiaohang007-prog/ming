import { expect, test } from "@playwright/test";
import type { Page } from "@playwright/test";

const sample = {
  name: "林清月", gender: "女", birthPlace: "杭州", calendar: "solar",
  birthDate: "2000-8-16", birthTime: "03:00", isLeapMonth: false
};

async function fillBirth(page: Page) {
  await page.getByLabel("姓名或称呼").fill(sample.name);
  await page.getByLabel("排盘性别").selectOption(sample.gender);
  await page.getByLabel("公历出生日期").fill("2000-08-16");
  await page.getByLabel("出生时间", { exact: true }).fill(sample.birthTime);
}

test("official example and solar/lunar inputs have the same twelve palaces", async ({ request }) => {
  const solar = await request.post("/api/chart/generate", { data: sample });
  expect(solar.status()).toBe(200);
  expect(solar.headers()["cache-control"]).toBe("no-store");
  const chart = await solar.json();
  // Expected values are from the iztro quick-start example, not generated by this test.
  expect(chart).toMatchObject({ source: "iztro", engineVersion: "2.6.1", soul: "破军", body: "文昌", fiveElementsClass: "木三局", earthlyBranchOfSoulPalace: "午", earthlyBranchOfBodyPalace: "戌" });
  expect(chart.palaces).toHaveLength(12);
  expect(chart.palaces.map((palace: { earthlyBranch: string }) => palace.earthlyBranch)).toEqual(["寅", "卯", "辰", "巳", "午", "未", "申", "酉", "戌", "亥", "子", "丑"]);
  const lunar = await request.post("/api/chart/generate", { data: { ...sample, calendar: "lunar", birthDate: "2000-7-17" } });
  expect(lunar.status()).toBe(200);
  expect((await lunar.json()).palaces).toEqual(chart.palaces);
  const renamed = await request.post("/api/chart/generate", { data: { ...sample, name: "另一个称呼", birthPlace: "" } });
  expect((await renamed.json()).palaces).toEqual(chart.palaces);
  expect(chart).not.toHaveProperty("risingSign");
});

test("invalid input, nonexistent lunar leap month and malformed JSON are rejected", async ({ request }) => {
  for (const input of [
    { ...sample, gender: "未设定" }, { ...sample, birthTime: "" },
    { ...sample, birthDate: "2023-2-29" },
    { ...sample, calendar: "lunar", birthDate: "2000-7-17", isLeapMonth: true }
  ]) {
    const response = await request.post("/api/chart/generate", { data: input });
    expect(response.status()).toBe(400);
    expect((await response.json()).error).toBeTruthy();
  }
  const malformed = await request.post("/api/chart/generate", { data: "{", headers: { "Content-Type": "application/json" } });
  expect(malformed.status()).toBe(400);
});

test("early and late Zi boundaries follow the fixed official day rule", async ({ request }) => {
  const charts = [];
  for (const birthTime of ["00:00", "00:59", "01:00", "22:59", "23:00", "23:59"]) {
    const response = await request.post("/api/chart/generate", { data: { ...sample, birthTime } });
    expect(response.status()).toBe(200); charts.push(await response.json());
  }
  expect(charts[0].palaces).toEqual(charts[1].palaces);
  expect(charts[4].palaces).toEqual(charts[5].palaces);
  expect(charts[0].timeRange).not.toEqual(charts[2].timeRange);
  expect(charts[3].timeRange).not.toEqual(charts[4].timeRange);
  const nextDay = await request.post("/api/chart/generate", { data: { ...sample, birthDate: "2000-8-17", birthTime: "00:00" } });
  const next = await nextDay.json();
  const facts = (chart: { palaces: { majorStars: { name: string; brightness: string; mutagen: string }[] }[] }) => chart.palaces.map((palace) => palace.majorStars.map((star) => ({ name: star.name, brightness: star.brightness, mutagen: star.mutagen })));
  expect(facts(charts[4])).toEqual(facts(next));
});

test("calendar switch clears the date and blank required fields cannot generate", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("button", { name: "生成命盘", exact: true }).click();
  await expect(page.locator('[name="gender"]')).toHaveAttribute("aria-invalid", "true");
  await expect(page.locator('[name="birthTime"]')).toHaveAttribute("aria-invalid", "true");
  await fillBirth(page);
  await page.getByRole("radio", { name: "农历", exact: true }).check();
  await expect(page.getByLabel("农历出生日期")).toHaveValue("");
  await page.getByLabel("农历出生日期").fill("2000-7-17");
  await page.route("**/api/chart/generate", (route) => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: "测试排盘服务不可用" }) }), { times: 1 });
  await page.getByRole("button", { name: "生成命盘", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "测试排盘服务不可用" })).toBeVisible();
  await page.getByRole("button", { name: "重新生成命盘", exact: true }).click();
  await expect(page.getByRole("heading", { name: "林清月的紫微命盘" })).toBeVisible();
});

